  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => Array.from(r.querySelectorAll(s));
  const pad = n => String(n).padStart(2, '0');

  /* ---------- 燈箱 ---------- */
  const lb = $('#lb');
  if (lb) {
    const img = $('img', lb), cap = $('.lb-cap', lb);
    let idx = 0;
    const byId = Object.fromEntries(SLIDES.map((s, i) => [s[0], i]));
    const show = i => {
      idx = (i + SLIDES.length) % SLIDES.length;
      const [id, , title, desc] = SLIDES[idx];
      img.src = `img/full/${id}.jpg`; img.alt = title;
      cap.innerHTML = `<div><span class="n">${pad(idx + 1)} / ${SLIDES.length}</span><b>${title}</b>${desc ? ` <span style="opacity:.8">— ${desc}</span>` : ''}</div>`;
      if (!lb.open) lb.showModal();
    };
    $('.prev', lb).addEventListener('click', () => show(idx - 1));
    $('.next', lb).addEventListener('click', () => show(idx + 1));
    $('.close', lb).addEventListener('click', () => lb.close());
    lb.addEventListener('click', e => { if (e.target === lb) lb.close(); });
    lb.addEventListener('keydown', e => { if (e.key === 'ArrowLeft') show(idx - 1); if (e.key === 'ArrowRight') show(idx + 1); });
    document.addEventListener('click', e => {
      const el = e.target.closest('[data-slide]');
      if (el && el.dataset.slide in byId) { e.preventDefault(); show(byId[el.dataset.slide]); }
    });
  }

